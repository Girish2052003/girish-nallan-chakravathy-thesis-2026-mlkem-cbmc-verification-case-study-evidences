def collect_algorithm_texts(rich: Dict[str, Any]) -> List[Dict[str, Any]]:
    data = rich.get("algorithm_blocks")
    blocks: List[Any] = []
    if isinstance(data, dict):
        for key in ("algorithm_blocks", "algorithms", "blocks", "items"):
            blocks.extend(as_list(data.get(key)))
    elif isinstance(data, list):
        blocks = data

    out: List[Dict[str, Any]] = []
    for i, block in enumerate(blocks, start=1):
        if isinstance(block, dict):
            text = normalize_space(
                block.get("text")
                or block.get("body")
                or block.get("algorithm_text")
                or block.get("raw")
                or flatten_text(block)
            )
            name = str(block.get("name") or block.get("algorithm_name") or f"algorithm_{i}")
            evidence = block.get("evidence") or {
                "source_file": "01_algorithm_blocks.json",
                "start_line": block.get("start_line"),
                "end_line": block.get("end_line"),
            }
        else:
            text = normalize_space(block)
            name = f"algorithm_{i}"
            evidence = {"source_file": "01_algorithm_blocks.json"}
        if text:
            out.append({"name": name, "text": text, "evidence": evidence})
    return out


def collect_algorithm_assignments(rich: Dict[str, Any]) -> List[Dict[str, Any]]:
    assignments: List[Dict[str, Any]] = []
    for block in collect_algorithm_texts(rich):
        text = block["text"]
        # Accept ASCII =, <-, ←, := as assignment-like.
        for m in re.finditer(r"([A-Za-z_][A-Za-z0-9_\.\-\>\[\]]+)\s*(?:<-|←|:=|=)\s*([^;\n]+)", text):
            assignments.append({
                "lhs": normalize_space(m.group(1)),
                "rhs": normalize_space(m.group(2)),
                "algorithm": block["name"],
                "evidence": block["evidence"],
                "raw": normalize_space(m.group(0)),
            })

    # Some Agent 2 v2 schemas store steps explicitly.
    data = rich.get("algorithm_blocks")
    candidates: List[Any] = []
    if isinstance(data, dict):
        for key in ("algorithm_blocks", "algorithms", "blocks", "items"):
            for block in as_list(data.get(key)):
                if isinstance(block, dict):
                    candidates.extend(as_list(block.get("steps")))
                    candidates.extend(as_list(block.get("operations")))
                    candidates.extend(as_list(block.get("assignments")))
    for item in candidates:
        if isinstance(item, dict):
            lhs = item.get("lhs") or item.get("left")
            rhs = item.get("rhs") or item.get("right") or item.get("expression")
            if lhs and rhs:
                assignments.append({
                    "lhs": normalize_space(lhs),
                    "rhs": normalize_space(rhs),
                    "algorithm": str(item.get("algorithm") or item.get("algorithm_name") or "unknown_algorithm"),
                    "evidence": item.get("evidence") or {"source_file": "01_algorithm_blocks.json"},
                    "raw": normalize_space(flatten_text(item)),
                })
    return assignments


def collect_prepost_texts(rich: Dict[str, Any]) -> List[Dict[str, Any]]:
    data = rich.get("preconditions_postconditions")
    out: List[Dict[str, Any]] = []
    if isinstance(data, dict):
        for bucket in ("preconditions", "postconditions", "input_requirements", "output_guarantees", "items"):
            for item in as_list(data.get(bucket)):
                text = normalize_space(flatten_text(item if isinstance(item, str) else item.get("text") or item.get("description") or item))
                if text:
                    out.append({"kind": bucket, "text": text, "evidence": item.get("evidence") if isinstance(item, dict) else {"source_file": "01_preconditions_postconditions.json"}})
    elif isinstance(data, list):
        for item in data:
            text = normalize_space(flatten_text(item))
            if text:
                out.append({"kind": "item", "text": text, "evidence": {"source_file": "01_preconditions_postconditions.json"}})
    return out


def collect_constraints_texts(rich: Dict[str, Any]) -> List[Dict[str, Any]]:
    data = rich.get("equations_constraints")
    out: List[Dict[str, Any]] = []
    if isinstance(data, dict):
        for bucket in ("equations", "constraints", "ranges", "relations", "items"):
            for item in as_list(data.get(bucket)):
                text = normalize_space(flatten_text(item if isinstance(item, str) else item.get("text") or item.get("expression") or item))
                if text:
                    out.append({"kind": bucket, "text": text, "evidence": item.get("evidence") if isinstance(item, dict) else {"source_file": "01_equations_constraints.json"}})
    elif isinstance(data, list):
        for item in data:
            text = normalize_space(flatten_text(item))
            if text:
                out.append({"kind": "item", "text": text, "evidence": {"source_file": "01_equations_constraints.json"}})
    return out


def rich_uncertainty_texts(spec_summary: Dict[str, Any], properties: Dict[str, Any], manifest: Dict[str, Any], rich: Dict[str, Any]) -> List[str]:
    texts: List[str] = []
    for source in (spec_summary, properties, manifest, rich.get("agent2v2_integration_report", {}), rich.get("spec_grounding_report", {})):
        if isinstance(source, dict):
            for key in ("uncertainties", "quality_flags", "warnings", "known_limitations", "human_review_flags"):
                for item in as_list(source.get(key)):
                    text = normalize_space(flatten_text(item))
                    if text:
                        texts.append(text)
    return list(dict.fromkeys(texts))


def assumption_has_traceability(assumption: Dict[str, Any], manifest: Dict[str, Any], rich: Dict[str, Any]) -> Tuple[bool, str]:
    expr = assumption.get("expression", "")
    expr_tokens = token_set(expr)
    if not expr_tokens:
        return False, "empty assumption expression"

    # Agent 5 v2 CSV traceability is strongest.
    for row in rich.get("harness_assumption_traceability_rows", []):
        row_text = flatten_text(row)
        if expr in row_text or len(expr_tokens & token_set(row_text)) >= max(2, min(4, len(expr_tokens))):
            return True, "matched 04_harness_assumption_traceability.csv"

    for item in as_list(manifest.get("candidate_assumptions_inserted")):
        text = flatten_text(item)
        if expr in text or len(expr_tokens & token_set(text)) >= max(2, min(4, len(expr_tokens))):
            return True, "matched 04_artifact_manifest.json candidate_assumptions_inserted"

    # Preconditions/constraints can support numeric bounds, but not automatically if vague.
    for item in collect_prepost_texts(rich) + collect_constraints_texts(rich):
        text = item["text"]
        if len(expr_tokens & token_set(text)) >= max(2, min(4, len(expr_tokens))):
            return True, f"matched {item['kind']} from rich spec context"

    return False, "no direct traceability evidence found"


def assertion_algorithm_alignment(assertion: Dict[str, Any], rich: Dict[str, Any], manifest: Dict[str, Any], properties: Dict[str, Any]) -> Dict[str, Any]:
    expr = assertion.get("expression", "")
    expr_norm = expr.replace("->", ".")
    expr_tokens = token_set(expr_norm)
    best = {
        "assertion": expr,
        "line": assertion.get("line"),
        "alignment_status": "not_checked",
        "best_algorithm": "",
        "best_algorithm_step": "",
        "score": 0.0,
        "evidence": {},
        "note": "",
    }

    assignments = collect_algorithm_assignments(rich)
    for assign in assignments:
        candidate_text = f"{assign.get('lhs')} {assign.get('rhs')} {assign.get('raw')}".replace("->", ".")
        cand_tokens = token_set(candidate_text)
        if not cand_tokens:
            continue
        overlap = len(expr_tokens & cand_tokens)
        denom = max(1, min(len(expr_tokens), len(cand_tokens)))
        score = overlap / denom
        if score > best["score"]:
            best.update({
                "alignment_status": "aligned_candidate" if score >= 0.35 else "weak_alignment",
                "best_algorithm": assign.get("algorithm", ""),
                "best_algorithm_step": assign.get("raw", ""),
                "score": round(score, 3),
                "evidence": assign.get("evidence") or {},
                "note": "Token overlap against parsed algorithm assignment.",
            })

    # Agent 5 v2 assertion plan can also support assertions.
    plan = rich.get("spec_grounded_assertion_plan")
    for item in as_list(plan.get("assertions") if isinstance(plan, dict) else []):
        text = flatten_text(item)
        score = len(expr_tokens & token_set(text)) / max(1, min(len(expr_tokens), len(token_set(text)) or 1))
        if score > best["score"]:
            best.update({
                "alignment_status": "aligned_candidate" if score >= 0.35 else "weak_alignment",
                "best_algorithm": "04_spec_grounded_assertion_plan",
                "best_algorithm_step": text[:300],
                "score": round(score, 3),
                "evidence": item.get("evidence") if isinstance(item, dict) else {"source_file": "04_spec_grounded_assertion_plan.json"},
                "note": "Matched Agent 5 v2 assertion plan.",
            })

    if not assignments and not plan:
        best["alignment_status"] = "no_algorithm_or_assertion_plan_available"
        best["note"] = "Agent 2/5 v2 rich algorithm/assertion-plan files were not available."
    elif best["score"] < 0.2:
        best["alignment_status"] = "not_aligned"
        best["note"] = "No strong match to parsed algorithm assignments or assertion plan."
    return best


def detect_symbol_misuse(artifact_text: str, constants: Dict[str, Any], rich: Dict[str, Any]) -> List[Dict[str, Any]]:
    findings: List[Dict[str, Any]] = []
    q_val = constant_value(constants, "q")
    n_val = constant_value(constants, "N")
    lower = artifact_text.lower()

    # q used as raw coefficient input bound is suspicious unless preconditions mention input coefficient ranges.
    if q_val is not None and str(q_val) in artifact_text and "__CPROVER_assume" in artifact_text:
        prepost_text = "\n".join(x["text"].lower() for x in collect_prepost_texts(rich) + collect_constraints_texts(rich))
        if not re.search(r"(input|coefficient|coeffs).{0,80}(range|bound|<|>|≤|≥|between)", prepost_text):
            findings.append({
                "severity": "medium",
                "type": "q_used_without_input_range_context",
                "message": f"The harness uses q={q_val} in/near assumptions, but parsed preconditions do not clearly justify q as an input coefficient bound.",
                "recommendation": "Use q as modulus context only unless the selected FIPS/spec section explicitly states the input coefficient range.",
            })

    if n_val is not None:
        uses_n = str(n_val) in artifact_text or re.search(r"\b(KYBER_N|MLKEM_N|MLK_N|N)\b", artifact_text)
        if not uses_n and re.search(r"\bfor\s*\(", artifact_text):
            findings.append({
                "severity": "medium",
                "type": "n_not_used_for_loop_bound",
                "message": f"Spec/parameter table indicates N={n_val}, but harness loops do not visibly use N or a compatible implementation macro/literal.",
                "recommendation": "Use the implementation macro for polynomial size or document why another loop bound is correct.",
            })

    # Symbols that are common but absent from rich symbol table.
    symbol_table_text = flatten_text(rich.get("symbol_table", {})).lower()
    for sym in sorted(set(re.findall(r"\b(eta1|eta2|du|dv|k|q|n)\b", lower))):
        if sym not in symbol_table_text and sym not in {"q", "n"}:
            findings.append({
                "severity": "low",
                "type": "symbol_used_without_symbol_table_entry",
                "message": f"Symbol `{sym}` appears in the artifact but was not found in the parsed symbol table.",
                "recommendation": "Confirm whether the symbol comes from code macros, selected FIPS parameters, or an unsupported assumption.",
            })

    return findings


def check_uncertainty_handling(artifact_text: str, manifest: Dict[str, Any], rich: Dict[str, Any], uncertainties: List[str]) -> Dict[str, Any]:
    review_markers = ["human review", "candidate", "uncertain", "needs review", "critic"]
    combined = (artifact_text + "\n" + flatten_text(manifest)).lower()
    markers_present = [m for m in review_markers if m in combined]

    high_uncertainty_count = len(uncertainties)
    if high_uncertainty_count == 0:
        status = "no_uncertainties_recorded"
        severity = "info"
        message = "No upstream uncertainties were recorded."
    elif markers_present:
        status = "acknowledged"
        severity = "info"
        message = f"{high_uncertainty_count} uncertainty/limitation item(s) exist and artifact/manifest contains review markers."
    else:
        status = "ignored_or_not_visible"
        severity = "medium"
        message = f"{high_uncertainty_count} uncertainty/limitation item(s) exist, but the harness/manifest does not visibly acknowledge them."

    return {
        "status": status,
        "severity": severity,
        "message": message,
        "markers_present": markers_present,
        "uncertainty_count": high_uncertainty_count,
        "sample_uncertainties": uncertainties[:10],
    }


