def indexed_lines(text: str) -> List[Tuple[int, str]]:
    return list(enumerate((text or "").splitlines(), start=1))


def evidence_for_line(path: Path, line_no: int, line: str) -> Dict[str, Any]:
    return {
        "source_file": str(path),
        "start_line": line_no,
        "end_line": line_no,
        "text": line.strip(),
    }


def find_lines_matching(text: str, pattern: str, flags: int = 0) -> List[Tuple[int, str, re.Match[str]]]:
    out: List[Tuple[int, str, re.Match[str]]] = []
    rx = re.compile(pattern, flags)
    for line_no, line in indexed_lines(text):
        m = rx.search(line)
        if m:
            out.append((line_no, line, m))
    return out


def classify_assumption(expr: str) -> str:
    e = expr.replace(" ", "").lower()
    if e in {"0", "false", "(0)", "(false)"}:
        return "contradictory_or_vacuous"
    if e in {"1", "true", "(1)", "(true)"}:
        return "trivial"
    if re.search(r"coeffs\s*\[.*?\]\s*(<=|<|>=|>)\s*-?\d+", expr):
        return "coefficient_numeric_bound"
    if re.search(r"\w+\s*!=\s*null|\w+\s*!=\s*0", expr, re.I):
        return "pointer_non_null"
    if re.search(r"\w+\s*<\s*\w+|\w+\s*<=\s*\w+", expr):
        return "relational_bound"
    return "general_assumption"


def classify_assertion(expr: str) -> str:
    e = expr.replace(" ", "").lower()
    if e in {"1", "true", "(1)", "(true)"}:
        return "trivial"
    if e in {"0", "false", "(0)", "(false)"}:
        return "always_fails"
    if "==" in expr and "coeffs" in expr:
        return "coefficient_functional_equality"
    if "<" in expr or ">" in expr:
        return "range_or_bounds_assertion"
    return "general_assertion"


def extract_assumptions(text: str, path: Path) -> List[Dict[str, Any]]:
    assumptions: List[Dict[str, Any]] = []
    for line_no, line, m in find_lines_matching(text, r"__CPROVER_assume\s*\((.*)\)\s*;"):
        expr = normalize_space(m.group(1))
        assumptions.append({
            "expression": expr,
            "line": line_no,
            "evidence": evidence_for_line(path, line_no, line),
            "classification": classify_assumption(expr),
        })
    return assumptions


def extract_assertions(text: str, path: Path) -> List[Dict[str, Any]]:
    assertions: List[Dict[str, Any]] = []
    for line_no, line, m in find_lines_matching(text, r"\bassert\s*\((.*)\)\s*;"):
        expr = normalize_space(m.group(1))
        assertions.append({
            "expression": expr,
            "line": line_no,
            "evidence": evidence_for_line(path, line_no, line),
            "classification": classify_assertion(expr),
        })
    return assertions


def extract_includes(text: str, path: Path) -> List[Dict[str, Any]]:
    includes: List[Dict[str, Any]] = []
    for line_no, line, m in find_lines_matching(text, r"^\s*#\s*include\s*([<\"].*[>\"])"):
        includes.append({"include": m.group(1), "line": line_no, "evidence": evidence_for_line(path, line_no, line)})
    return includes


def extract_loops(text: str, path: Path) -> List[Dict[str, Any]]:
    loops: List[Dict[str, Any]] = []
    for line_no, line, m in find_lines_matching(text, r"\bfor\s*\((.*?)\)"):
        raw = normalize_space(m.group(1))
        parts = [p.strip() for p in raw.split(";")]
        loops.append({
            "kind": "for",
            "raw": raw,
            "init": parts[0] if len(parts) > 0 else "",
            "condition": parts[1] if len(parts) > 1 else "",
            "increment": parts[2] if len(parts) > 2 else "",
            "line": line_no,
            "evidence": evidence_for_line(path, line_no, line),
        })
    for line_no, line, m in find_lines_matching(text, r"\bwhile\s*\((.*?)\)"):
        loops.append({
            "kind": "while",
            "raw": normalize_space(m.group(1)),
            "condition": normalize_space(m.group(1)),
            "line": line_no,
            "evidence": evidence_for_line(path, line_no, line),
        })
    return loops


def extract_array_accesses(text: str, path: Path) -> List[Dict[str, Any]]:
    accesses: List[Dict[str, Any]] = []
    for line_no, line in indexed_lines(strip_c_comments(text)):
        for m in re.finditer(r"([A-Za-z_]\w*(?:->|\.)?[A-Za-z_]\w*)\s*\[\s*([^\]]+)\s*\]", line):
            accesses.append({
                "access": f"{m.group(1)}[{m.group(2).strip()}]",
                "base": m.group(1),
                "index": m.group(2).strip(),
                "line": line_no,
                "evidence": evidence_for_line(path, line_no, line),
            })
    return accesses


def extract_nondet_uses(text: str, path: Path) -> List[Dict[str, Any]]:
    uses: List[Dict[str, Any]] = []
    for line_no, line, m in find_lines_matching(text, r"\b(nondet_[A-Za-z0-9_]+)\s*\("):
        uses.append({"function": m.group(1), "line": line_no, "evidence": evidence_for_line(path, line_no, line)})
    return uses


def extract_function_calls(text: str) -> List[Dict[str, Any]]:
    clean = strip_c_comments(text)
    calls: List[Dict[str, Any]] = []
    keywords = {
        "if", "for", "while", "switch", "return", "sizeof", "assert", "__CPROVER_assume",
        "void", "int", "uint16_t", "int16_t", "uint32_t", "int32_t", "uint64_t", "int64_t",
    }
    for line_no, line in indexed_lines(clean):
        for m in re.finditer(r"\b([A-Za-z_]\w*)\s*\(", line):
            name = m.group(1)
            if name in keywords or name.startswith("nondet_"):
                continue
            if re.search(rf"\b{name}\s*\([^;]*\)\s*\{{", line):
                continue
            calls.append({"name": name, "line": line_no, "text": normalize_space(line)})
    return calls


def harness_declares_function(text: str, harness_function: str) -> bool:
    if not harness_function:
        return False
    return re.search(rf"\bvoid\s+{re.escape(harness_function)}\s*\(", text or "") is not None


def target_call_present(text: str, target_function: str) -> List[Dict[str, Any]]:
    if not target_function:
        return []
    calls: List[Dict[str, Any]] = []
    rx = re.compile(rf"\b{re.escape(target_function)}\s*\(")
    for line_no, line in indexed_lines(strip_c_comments(text)):
        if rx.search(line):
            # Avoid counting declarations/definitions where possible.
            if re.search(rf"^\s*(extern\s+)?[A-Za-z_][A-Za-z0-9_\s\*]*\b{re.escape(target_function)}\s*\(", line) and line.strip().endswith(";"):
                continue
            calls.append({"line": line_no, "evidence": evidence_for_line(Path("artifact"), line_no, line)})
    return calls


