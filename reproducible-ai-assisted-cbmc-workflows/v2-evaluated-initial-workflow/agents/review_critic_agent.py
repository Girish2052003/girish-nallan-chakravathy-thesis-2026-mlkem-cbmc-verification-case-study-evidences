def get_spec_constants(spec_summary: Dict[str, Any], rich: Dict[str, Any]) -> Dict[str, Any]:
    constants = spec_summary.get("constants", {})
    out: Dict[str, Any] = dict(constants) if isinstance(constants, dict) else {}

    # Merge Agent 2 v2 parameter table/symbol info conservatively.
    param_table = rich.get("parameter_table")
    if isinstance(param_table, dict):
        for bucket in ("parameters", "constants", "rows"):
            for item in as_list(param_table.get(bucket)):
                if isinstance(item, dict):
                    name = item.get("name") or item.get("symbol") or item.get("parameter")
                    value = item.get("value")
                    if name and value is not None and str(name) not in out:
                        out[str(name)] = {"value": value, "source": "01_parameter_table.json"}

    symbol_table = rich.get("symbol_table")
    if isinstance(symbol_table, dict):
        for item in as_list(symbol_table.get("symbols")) + as_list(symbol_table.get("entries")):
            if isinstance(item, dict):
                name = item.get("symbol") or item.get("name")
                value = item.get("value")
                if name and value is not None and str(name) not in out:
                    out[str(name)] = {"value": value, "source": "01_symbol_table.json"}

    return out


def constant_value(constants: Dict[str, Any], name: str) -> Optional[Any]:
    aliases = {
        "N": ["N", "n", "KYBER_N", "MLKEM_N", "MLK_N"],
        "q": ["q", "Q", "KYBER_Q", "MLKEM_Q", "MLK_Q"],
    }.get(name, [name])
    for alias in aliases:
        item = constants.get(alias)
        if isinstance(item, dict):
            return item.get("value")
        if item is not None:
            return item
    return None


