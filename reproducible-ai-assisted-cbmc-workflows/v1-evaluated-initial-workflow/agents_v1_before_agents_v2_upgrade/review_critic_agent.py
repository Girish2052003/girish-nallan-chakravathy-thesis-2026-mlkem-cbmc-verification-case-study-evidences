def get_target_function(config: Dict[str, Any], code_summary: Dict[str, Any], manifest: Dict[str, Any]) -> str:
    return str(
        manifest.get("target_function")
        or code_summary.get("target_function_detected")
        or code_summary.get("target_function_requested")
        or config.get("target_function")
        or ""
    ).strip()


def get_harness_function(config: Dict[str, Any], manifest: Dict[str, Any], target_function: str) -> str:
    return str(
        manifest.get("harness_function")
        or config.get("harness_function")
        or (f"harness_{target_function}" if target_function else "")
    ).strip()


def get_spec_constants(spec_summary: Dict[str, Any]) -> Dict[str, Any]:
    constants = spec_summary.get("constants", {})
    if isinstance(constants, dict):
        return constants
    return {}


def constant_value(constants: Dict[str, Any], name: str) -> Optional[Any]:
    item = constants.get(name) or constants.get(name.upper()) or constants.get(name.lower())
    if isinstance(item, dict):
        return item.get("value")
    return item


def spec_has_supported_bound(spec_summary: Dict[str, Any]) -> bool:
    """Return True only when the spec summary explicitly mentions coefficient value bounds.

    q and N alone do not automatically justify a harness assumption like coeff >= -3329.
    We intentionally keep this conservative.
    """
    buckets = [
        "input_assumptions",
        "candidate_output_guarantees",
        "candidate_safety_properties",
        "candidate_functional_properties",
    ]
    bound_keywords = ["coefficient", "coeffs", "bound", "range", "between", "less than", "greater than", "<=", ">=", "valid input bound"]
    for bucket in buckets:
        for item in as_list(spec_summary.get(bucket)):
            text = json.dumps(item, ensure_ascii=False).lower() if isinstance(item, (dict, list)) else str(item).lower()
            if "coefficient" in text and any(k in text for k in bound_keywords) and re.search(r"[<>]=?|between", text):
                return True
    return False


def code_has_coeff_addition(code_summary: Dict[str, Any], artifact_text: str) -> bool:
    text = json.dumps(code_summary, ensure_ascii=False) + "\n" + artifact_text
    return bool(re.search(r"coeffs\s*\[.*?\].*\+.*coeffs\s*\[", text, flags=re.S))


def code_uses_signed_small_int(code_summary: Dict[str, Any], artifact_text: str) -> bool:
    text = (json.dumps(code_summary, ensure_ascii=False) + "\n" + artifact_text).lower()
    return any(token in text for token in ["int16_t", "int8_t", "signed", "nondet_int16_t", "nondet_int8_t"])


def selected_properties(properties: Dict[str, Any], manifest: Dict[str, Any]) -> List[Dict[str, Any]]:
    selected = manifest.get("selected_properties_used")
    if isinstance(selected, list):
        return [p for p in selected if isinstance(p, dict)]
    candidates = properties.get("candidate_properties")
    if isinstance(candidates, list):
        return [p for p in candidates if isinstance(p, dict)]
    return []


