def issue(
    severity: str,
    issue_type: str,
    message: str,
    recommendation: str,
    evidence: Optional[Dict[str, Any]] = None,
    related_property_ids: Optional[List[str]] = None,
) -> Dict[str, Any]:
    data: Dict[str, Any] = {
        "severity": severity,
        "type": issue_type,
        "message": message,
        "recommendation": recommendation,
    }
    if evidence:
        data["evidence"] = evidence
    if related_property_ids:
        data["related_property_ids"] = related_property_ids
    return data


def highest_severity(issues: List[Dict[str, Any]]) -> str:
    rank = {"info": 0, "low": 1, "medium": 2, "high": 3, "critical": 4}
    if not issues:
        return "none"
    return max((str(i.get("severity", "info")).lower() for i in issues), key=lambda s: rank.get(s, 0))


def review_status_from_issues(issues: List[Dict[str, Any]], artifact_exists: bool) -> str:
    if not artifact_exists:
        return "reject"
    severities = [str(i.get("severity", "info")).lower() for i in issues]
    if "critical" in severities or "high" in severities:
        return "needs_revision"
    if "medium" in severities:
        # Important: the Master Orchestrator treats high/critical as blocking, and this status
        # lets the artifact go to CBMC while preserving warnings for later repair/reporting.
        return "conditional_accept_for_tool"
    return "accept_for_tool"


def score_from_issues(issues: List[Dict[str, Any]]) -> Dict[str, Any]:
    weights = {"critical": 40, "high": 25, "medium": 10, "low": 3, "info": 1}
    raw = sum(weights.get(str(i.get("severity", "info")).lower(), 1) for i in issues)
    risk = min(100, raw)
    quality = max(0, 100 - risk)
    return {
        "risk_score_0_to_100": risk,
        "quality_score_0_to_100": quality,
        "highest_severity": highest_severity(issues),
        "issue_count": len(issues),
        "severity_counts": {
            sev: sum(1 for i in issues if str(i.get("severity", "")).lower() == sev)
            for sev in ["critical", "high", "medium", "low", "info"]
        },
    }


