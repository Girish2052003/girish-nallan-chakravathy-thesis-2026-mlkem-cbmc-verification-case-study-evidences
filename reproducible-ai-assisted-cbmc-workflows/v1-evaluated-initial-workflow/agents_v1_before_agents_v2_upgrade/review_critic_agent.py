def determine_artifact_path(run_dir: Path, project_root: Path, config: Dict[str, Any], args: argparse.Namespace) -> Path:
    # Priority: command-line --artifact, status current_artifact, config current_artifact, default.
    if args.artifact:
        p = Path(args.artifact).expanduser()
        if not p.is_absolute():
            # If just a filename, it usually lives in run_dir; otherwise project root.
            p = run_dir / p if len(p.parts) == 1 else project_root / p
        return p.resolve()

    status = read_json(run_dir / "status.json", default={})
    current = status.get("current_artifact") or config.get("current_artifact")
    if current:
        p = Path(str(current)).expanduser()
        if not p.is_absolute():
            p = run_dir / p if len(p.parts) == 1 else project_root / p
        return p.resolve()

    return (run_dir / DEFAULT_ARTIFACT).resolve()


def maybe_find_manifest(run_dir: Path, artifact_path: Path) -> Path:
    # For now Agent 5 writes 04_artifact_manifest.json. Later repaired artifacts may still use it.
    candidates = [
        run_dir / "04_artifact_manifest.json",
        run_dir / "04_generated_artifact_notes.json",
        artifact_path.with_suffix(".manifest.json"),
    ]
    for p in candidates:
        if p.exists():
            return p
    return run_dir / "04_artifact_manifest.json"


def run_agent(args: argparse.Namespace) -> int:
    started_at = utc_now()
    config_path = Path(args.config).expanduser().resolve()
    project_root = find_project_root(config_path)
    config = read_json(config_path)

    run_dir = Path(args.run_dir).expanduser() if args.run_dir else None
    if run_dir is None:
        run_id = str(config.get("run_id") or "run_001")
        run_dir = project_root / "runs" / run_id
    elif not run_dir.is_absolute():
        run_dir = project_root / run_dir
    run_dir = run_dir.resolve()
    run_dir.mkdir(parents=True, exist_ok=True)

    events_path = run_dir / "events.jsonl"
    append_jsonl(
        events_path,
        {
            "time": started_at,
            "agent": AGENT_NAME,
            "event_type": "started",
            "run_dir": str(run_dir),
            "config": str(config_path),
            "iteration": args.iteration,
        },
    )

    spec_path = run_dir / "01_spec_summary.json"
    code_path = run_dir / "02_code_summary.json"
    props_path = run_dir / "03_candidate_properties.json"

    artifact_path = determine_artifact_path(run_dir, project_root, config, args)
    manifest_path = maybe_find_manifest(run_dir, artifact_path)

    spec_summary = read_json(spec_path, default={})
    code_summary = read_json(code_path, default={})
    properties = read_json(props_path, default={})
    manifest = read_json(manifest_path, default={})
    artifact_text = read_text_if_exists(artifact_path)

    prompt_text = build_prompt_record(config, spec_summary, code_summary, properties, manifest, artifact_text, artifact_path)
    prompt_path = run_dir / "llm_prompts" / "05_critic_review_prompt.txt"
    write_text(prompt_path, prompt_text)

    extracted = run_critic_rules(
        artifact_path=artifact_path,
        artifact_text=artifact_text,
        config=config,
        spec_summary=spec_summary,
        code_summary=code_summary,
        properties=properties,
        manifest=manifest,
        iteration=args.iteration,
    )

    issues = as_list(extracted.get("issues"))
    artifact_exists = artifact_path.exists() and bool(artifact_text.strip())
    review_status = review_status_from_issues(issues, artifact_exists)
    quality_metrics = score_from_issues(issues)

    blocking = any(str(i.get("severity", "")).lower() in {"critical", "high"} for i in issues)
    tool_allowed = artifact_exists and not blocking
    repair_before_tool = artifact_exists and blocking

    if not artifact_exists:
        next_action = "Re-run Formal Artifact Generation Agent before attempting CBMC."
    elif repair_before_tool:
        next_action = "Send the artifact to Repair / Refinement Agent before CBMC because high/critical critic issues were found."
    elif review_status == "conditional_accept_for_tool":
        next_action = "Artifact may go to Formal Tool Execution Agent, but preserve critic warnings for counterexample analysis and human review."
    else:
        next_action = "Artifact may go to Formal Tool Execution Agent; human review is still required."

    review: Dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "agent": AGENT_NAME,
        "created_at": utc_now(),
        "started_at": started_at,
        "finished_at": utc_now(),
        "iteration": args.iteration,
        "review_status": review_status,
        "status": review_status,
        "artifact": str(artifact_path),
        "artifact_sha256_16": sha256_short(artifact_text) if artifact_text else None,
        "artifact_exists": artifact_exists,
        "artifact_manifest": str(manifest_path),
        "input_files": {
            "config": str(config_path),
            "spec_summary": str(spec_path),
            "code_summary": str(code_path),
            "candidate_properties": str(props_path),
            "artifact_manifest": str(manifest_path),
            "artifact": str(artifact_path),
        },
        "target_function": extracted.get("target_function"),
        "harness_function": extracted.get("harness_function"),
        "selected_property_types": extracted.get("selected_property_types", []),
        "selected_property_ids": extracted.get("selected_property_ids", []),
        "review_checklist": extracted.get("checklist", []),
        "issues": issues,
        "recommended_fix": [i.get("recommendation") for i in issues if i.get("recommendation")],
        "positive_findings": extracted.get("positive_findings", []),
        "quality_metrics": quality_metrics,
        "tool_execution_allowed": tool_allowed,
        "repair_recommended_before_tool": repair_before_tool,
        "human_review_required": True,
        "next_recommended_action": next_action,
        "assumption_review": {
            "count": len(as_list(extracted.get("assumptions"))),
            "assumptions": extracted.get("assumptions", []),
        },
        "assertion_review": {
            "count": len(as_list(extracted.get("assertions"))),
            "assertions": extracted.get("assertions", []),
        },
        "cbmc_readiness": {
            "manifest_command_seen": extracted.get("manifest_command_seen", ""),
            "target_call_count": len(as_list(extracted.get("target_calls"))),
            "loop_count": len(as_list(extracted.get("loops"))),
            "array_access_count": len(as_list(extracted.get("array_accesses"))),
            "nondet_input_count": len(as_list(extracted.get("nondet_uses"))),
            "spec_constants_seen": extracted.get("spec_constants_seen", {}),
        },
        "property_coverage": extracted.get("property_coverage", []),
        "scientific_guardrail": {
            "claim": "This review does not prove correctness; it only reviews candidate artifact quality before CBMC and human inspection.",
            "llm_or_deterministic": "deterministic_static_review",
            "formal_tool_and_human_are_authority": True,
        },
    }

    review_path = run_dir / "05_critic_review.json"
    md_path = run_dir / "05_critic_review.md"
    status_path = run_dir / "agent_status" / "05_critic_review_status.json"

    write_json(review_path, review)
    write_text(md_path, render_markdown(review))
    write_json(
        status_path,
        {
            "agent": AGENT_NAME,
            "status": "passed" if artifact_exists else "failed",
            "review_status": review_status,
            "tool_execution_allowed": tool_allowed,
            "repair_recommended_before_tool": repair_before_tool,
            "started_at": started_at,
            "finished_at": review["finished_at"],
            "outputs": {
                "review_json": str(review_path),
                "review_markdown": str(md_path),
                "prompt": str(prompt_path),
            },
            "human_review_required": True,
        },
    )

    append_jsonl(
        events_path,
        {
            "time": utc_now(),
            "agent": AGENT_NAME,
            "event_type": "finished",
            "status": "ok" if artifact_exists else "failed",
            "review_status": review_status,
            "iteration": args.iteration,
            "issue_count": len(issues),
            "highest_severity": quality_metrics.get("highest_severity"),
            "tool_execution_allowed": tool_allowed,
            "outputs": {
                "review_json": str(review_path),
                "review_markdown": str(md_path),
                "prompt": str(prompt_path),
            },
        },
    )

    print(f"[OK] Review / Critic Agent wrote: {review_path}")
    print(f"[OK] Markdown review: {md_path}")
    print(f"[INFO] Review status: {review_status}")
    print(f"[INFO] Issues: {len(issues)} | Highest severity: {quality_metrics.get('highest_severity')}")
    print(f"[INFO] Tool execution allowed: {tool_allowed}")
    print("[NOTE] This is a critic review only; CBMC and human review remain the authority.")

    # Do not return nonzero for needs_revision: the Master Orchestrator decides repair from JSON.
    return 0 if artifact_exists else 2


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Agent 6: Review / Critic Agent")
    parser.add_argument("--config", required=True, help="Path to run config JSON, e.g., configs/poly_add_run.json")
    parser.add_argument("--run-dir", required=False, help="Run directory, e.g., runs/run_001_poly_add")
    parser.add_argument("--iteration", type=int, default=0, help="Refinement iteration number")
    parser.add_argument("--artifact", required=False, help="Optional artifact filename/path to review, e.g., 04_generated_harness.c")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = build_arg_parser()
    args = parser.parse_args(argv)
    try:
        return run_agent(args)
    except Exception as exc:
        print(f"[ERROR] Review / Critic Agent failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
