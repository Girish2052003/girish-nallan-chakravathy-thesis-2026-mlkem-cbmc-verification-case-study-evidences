def build_prompt_record(
    config: Dict[str, Any],
    spec_summary: Dict[str, Any],
    code_summary: Dict[str, Any],
    properties: Dict[str, Any],
    manifest: Dict[str, Any],
    artifact_text: str,
    artifact_path: Path,
) -> str:
    target = get_target_function(config, code_summary, manifest)
    harness = get_harness_function(config, manifest, target)
    selected = selected_properties(properties, manifest)
    selected_short = [
        {
            "id": p.get("id"),
            "type": p.get("type"),
            "priority": p.get("priority"),
            "description": p.get("description"),
        }
        for p in selected[:20]
    ]
    return f"""You are the Review / Critic Agent for an AI-assisted formal-verification artifact workflow.

Task:
1. Review the generated CBMC harness.
2. Check whether assumptions are too strong or too weak.
3. Check whether assertions are meaningful and connected to selected properties.
4. Check whether the harness calls the correct target function.
5. Check whether constants/input ranges are justified by the selected spec/code summaries.
6. Check whether the artifact might prove something trivial or unsupported.
7. Produce severity-labelled issues and recommended fixes.
8. Do not claim the artifact is a proof.

Target function: {target}
Harness function: {harness}
Artifact path: {artifact_path}

Selected properties summary:
{json.dumps(selected_short, indent=2, ensure_ascii=False)}

Spec constants:
{json.dumps(get_spec_constants(spec_summary), indent=2, ensure_ascii=False)[:4000]}

Code function summary:
{json.dumps(code_summary.get('function', {}), indent=2, ensure_ascii=False)[:4000]}

Artifact preview:
```c
{artifact_text[:8000]}
```

Return a structured JSON review. This file records the deterministic critic task even when no external LLM is used.
"""


def render_markdown(review: Dict[str, Any]) -> str:
    score = review.get("quality_metrics", {})
    lines: List[str] = []
    lines.append("# 05 Critic Review")
    lines.append("")
    lines.append(f"**Agent:** `{AGENT_NAME}`")
    lines.append(f"**Review status:** `{review.get('review_status')}`")
    lines.append(f"**Target function:** `{review.get('target_function')}`")
    lines.append(f"**Harness function:** `{review.get('harness_function')}`")
    lines.append(f"**Artifact:** `{review.get('artifact')}`")
    lines.append(f"**Iteration:** `{review.get('iteration')}`")
    lines.append("")
    lines.append("## Scientific guardrail")
    lines.append("")
    lines.append("This review does not prove the artifact correct. It only checks whether the candidate artifact is reasonable enough to send to the formal tool or whether repair is needed first. CBMC and human review remain the authority.")
    lines.append("")
    lines.append("## Quality metrics")
    lines.append("")
    lines.append(f"- Risk score: `{score.get('risk_score_0_to_100')}` / 100")
    lines.append(f"- Quality score: `{score.get('quality_score_0_to_100')}` / 100")
    lines.append(f"- Highest severity: `{score.get('highest_severity')}`")
    lines.append(f"- Issue count: `{score.get('issue_count')}`")
    lines.append("")
    lines.append("## Decision")
    lines.append("")
    lines.append(f"- Tool execution allowed: `{review.get('tool_execution_allowed')}`")
    lines.append(f"- Repair recommended before tool: `{review.get('repair_recommended_before_tool')}`")
    lines.append(f"- Human review required: `{review.get('human_review_required')}`")
    lines.append("")

    lines.append("## Issues")
    lines.append("")
    issues = as_list(review.get("issues"))
    if not issues:
        lines.append("No blocking issues detected by the deterministic critic. Human review is still required.")
    else:
        for i, it in enumerate(issues, start=1):
            lines.append(f"### {i}. `{it.get('severity')}` — `{it.get('type')}`")
            lines.append("")
            lines.append(str(it.get("message", "")))
            lines.append("")
            lines.append(f"**Recommended fix:** {it.get('recommendation', '')}")
            ev = it.get("evidence")
            if isinstance(ev, dict) and ev.get("text"):
                lines.append("")
                lines.append(f"Evidence line {ev.get('start_line')}: `{ev.get('text')}`")
            lines.append("")

    lines.append("## Positive findings")
    lines.append("")
    positives = as_list(review.get("positive_findings"))
    if positives:
        for item in positives:
            lines.append(f"- {item}")
    else:
        lines.append("- No positive findings recorded.")
    lines.append("")

    lines.append("## Checklist")
    lines.append("")
    checklist = as_list(review.get("review_checklist"))
    if checklist:
        lines.append("| Check | Passed | Details |")
        lines.append("|---|---:|---|")
        for c in checklist:
            passed = "yes" if c.get("passed") else "no"
            details = str(c.get("details", "")).replace("|", "\\|")
            lines.append(f"| `{c.get('check')}` | {passed} | {details} |")
    else:
        lines.append("No checklist items recorded.")
    lines.append("")

    lines.append("## Property coverage")
    lines.append("")
    coverage = as_list(review.get("property_coverage"))
    if coverage:
        lines.append("| Property | Type | Coverage | Covered by |")
        lines.append("|---|---|---|---|")
        for c in coverage:
            covered_by = ", ".join(as_list(c.get("covered_by")))
            lines.append(f"| `{c.get('property_id')}` | `{c.get('property_type')}` | `{c.get('coverage_status')}` | {covered_by} |")
    else:
        lines.append("No selected property coverage map available.")
    lines.append("")

    lines.append("## Next recommended action")
    lines.append("")
    lines.append(str(review.get("next_recommended_action", "Human review required.")))
    lines.append("")
    return "\n".join(lines)


