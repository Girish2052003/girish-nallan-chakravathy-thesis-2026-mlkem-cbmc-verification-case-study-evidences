#!/usr/bin/env python3
"""
Agent 6: Review / Critic Agent
==============================

Purpose
-------
This agent reviews the candidate formal-verification artifact generated by Agent 5.
For the current thesis prototype, the artifact is usually a CBMC C harness:

  04_generated_harness.c

The critic reads:
  - 04_generated_harness.c (or the current artifact passed by the orchestrator)
  - 04_artifact_manifest.json
  - 01_spec_summary.json
  - 02_code_summary.json
  - 03_candidate_properties.json
  - config JSON

It produces:
  - 05_critic_review.json
  - 05_critic_review.md
  - llm_prompts/05_critic_review_prompt.txt
  - agent_status/05_critic_review_status.json

Scientific guardrail
--------------------
This agent DOES NOT prove the artifact correct. It is a deterministic reviewer that catches
obvious and common artifact problems before CBMC/formal-tool execution. CBMC and human
review remain the authority.

Design goals
------------
- Standard-library only.
- Deterministic and reproducible.
- Conservative: severe structural problems block tool execution; warnings are preserved.
- Compatible with the Master Orchestrator's decision logic.
- Produces both human-readable and machine-readable review output.

Typical use
-----------
python3 agents/review_critic_agent.py \
  --config configs/poly_add_run.json \
  --run-dir runs/run_001_poly_add \
  --iteration 0
"""

