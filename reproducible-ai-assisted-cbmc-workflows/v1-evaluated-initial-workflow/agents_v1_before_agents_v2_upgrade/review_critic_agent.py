def run_critic_rules(
    *,
    artifact_path: Path,
    artifact_text: str,
    config: Dict[str, Any],
    spec_summary: Dict[str, Any],
    code_summary: Dict[str, Any],
    properties: Dict[str, Any],
    manifest: Dict[str, Any],
    iteration: int,
) -> Dict[str, Any]:
    target_function = get_target_function(config, code_summary, manifest)
    harness_function = get_harness_function(config, manifest, target_function)
    selected = selected_properties(properties, manifest)
    selected_types = sorted({str(p.get("type", "unknown")) for p in selected})
    selected_ids = [str(p.get("id")) for p in selected if p.get("id")]

    artifact_exists = artifact_path.exists() and bool(artifact_text.strip())
    issues: List[Dict[str, Any]] = []
    positives: List[str] = []
    checklist: List[Dict[str, Any]] = []

    assumptions = extract_assumptions(artifact_text, artifact_path) if artifact_exists else []
    assertions = extract_assertions(artifact_text, artifact_path) if artifact_exists else []
    includes = extract_includes(artifact_text, artifact_path) if artifact_exists else []
    loops = extract_loops(artifact_text, artifact_path) if artifact_exists else []
    array_accesses = extract_array_accesses(artifact_text, artifact_path) if artifact_exists else []
    nondet_uses = extract_nondet_uses(artifact_text, artifact_path) if artifact_exists else []
    calls = extract_function_calls(artifact_text) if artifact_exists else []
    target_calls = target_call_present(artifact_text, target_function) if artifact_exists else []

    constants = get_spec_constants(spec_summary)
    spec_n = constant_value(constants, "N")
    spec_q = constant_value(constants, "q")
    manifest_cmd = str(manifest.get("recommended_cbmc_command") or manifest.get("cbmc_command") or "")
    if not manifest_cmd:
        # Some generated manifests store commands in nested structure.
        manifest_cmd = json.dumps(manifest.get("recommended_commands", ""), ensure_ascii=False)

    def add_check(name: str, passed: bool, details: str, severity_if_failed: str = "medium") -> None:
        checklist.append({"check": name, "passed": passed, "details": details, "severity_if_failed": severity_if_failed})

    # 1. Artifact existence and basic shape.
    if not artifact_exists:
        issues.append(
            issue(
                "critical",
                "missing_artifact",
                f"The expected artifact file was not found or is empty: {artifact_path}",
                "Re-run the Formal Artifact Generation Agent and confirm that 04_generated_harness.c is created.",
            )
        )
        add_check("artifact_exists", False, "Artifact file missing or empty", "critical")
        return {
            "target_function": target_function,
            "harness_function": harness_function,
            "selected_property_types": selected_types,
            "selected_property_ids": selected_ids,
            "assumptions": assumptions,
            "assertions": assertions,
            "includes": includes,
            "loops": loops,
            "array_accesses": array_accesses,
            "nondet_uses": nondet_uses,
            "function_calls": calls,
            "issues": issues,
            "positive_findings": positives,
            "checklist": checklist,
        }

    add_check("artifact_exists", True, f"Artifact found: {artifact_path}", "critical")
    positives.append("Artifact file exists and is non-empty.")

    # 2. Guardrail comments.
    lower_artifact = artifact_text.lower()
    has_candidate_guardrail = "candidate" in lower_artifact and ("does not prove" in lower_artifact or "must be reviewed" in lower_artifact)
    add_check(
        "scientific_guardrail_comment",
        has_candidate_guardrail,
        "Harness states candidate/non-proof status" if has_candidate_guardrail else "Harness does not clearly state candidate/non-proof status",
        "low",
    )
    if has_candidate_guardrail:
        positives.append("Artifact includes a candidate/non-proof guardrail comment.")
    else:
        issues.append(
            issue(
                "low",
                "missing_scientific_guardrail_comment",
                "The harness does not clearly state that it is only a candidate artifact and not a proof.",
                "Add a short header comment saying the artifact must be reviewed by the Critic Agent, CBMC, and the human researcher.",
            )
        )

    # 3. Harness function existence.
    has_harness = harness_declares_function(artifact_text, harness_function)
    add_check(
        "harness_function_declared",
        has_harness,
        f"Expected harness function `{harness_function}` declared" if has_harness else f"Expected harness function `{harness_function}` not declared",
        "high",
    )
    if has_harness:
        positives.append(f"Expected harness function `{harness_function}` is declared.")
    else:
        issues.append(
            issue(
                "high",
                "missing_harness_function",
                f"The artifact does not declare the expected harness function `{harness_function}`.",
                "Generate or rename the harness function so the CBMC command can target it with --function.",
            )
        )

    # 4. Target function call.
    add_check(
        "target_function_called",
        bool(target_calls),
        f"Target function `{target_function}` call found" if target_calls else f"No call to target function `{target_function}` found",
        "high",
    )
    if target_calls:
        positives.append(f"Artifact calls the target function `{target_function}`.")
    else:
        issues.append(
            issue(
                "high",
                "missing_target_call",
                f"The harness does not call the selected target function `{target_function}`.",
                "Call the exact selected implementation function; otherwise CBMC may verify only the harness scaffolding.",
            )
        )

    # 5. Include and type sanity.
    include_names = [x.get("include", "") for x in includes]
    has_assert_include = any("assert.h" in s for s in include_names)
    add_check("assert_header_included", has_assert_include, "assert.h included" if has_assert_include else "assert.h not included", "medium")
    if assertions and not has_assert_include:
        issues.append(
            issue(
                "medium",
                "missing_assert_header",
                "The harness uses assert(...) but does not visibly include <assert.h>.",
                "Include <assert.h> or ensure the build environment provides assert declarations safely.",
            )
        )
    elif has_assert_include:
        positives.append("Harness includes <assert.h> for C assertions.")

    # 6. Assumption checks.
    contradictory_assumptions = [a for a in assumptions if a.get("classification") == "contradictory_or_vacuous"]
    for a in contradictory_assumptions:
        issues.append(
            issue(
                "critical",
                "vacuous_assumption",
                f"The assumption `{a['expression']}` can make the proof vacuous or unreachable.",
                "Remove contradictory assumptions; every assumption should represent a real precondition.",
                a.get("evidence"),
            )
        )

    coefficient_bound_assumptions = [a for a in assumptions if a.get("classification") == "coefficient_numeric_bound"]
    has_explicit_spec_bound = spec_has_supported_bound(spec_summary)
    for a in coefficient_bound_assumptions:
        if not has_explicit_spec_bound:
            issues.append(
                issue(
                    "high",
                    "unsupported_coefficient_bound_assumption",
                    f"The coefficient bound assumption `{a['expression']}` may not be justified by the selected specification excerpt alone.",
                    "Either cite a precise input-bound rule from the selected spec/code context, or move this assumption into a human-reviewed experiment variant.",
                    a.get("evidence"),
                )
            )
    if coefficient_bound_assumptions and has_explicit_spec_bound:
        positives.append("Coefficient numeric assumptions exist and the spec summary appears to contain explicit bound evidence.")
    elif not coefficient_bound_assumptions:
        positives.append("No unsupported default coefficient range assumptions were inserted by the harness.")

    add_check(
        "no_contradictory_assumptions",
        not contradictory_assumptions,
        "No obviously contradictory assumptions found" if not contradictory_assumptions else "Contradictory/vacuous assumptions found",
        "critical",
    )

    # 7. Assertion checks.
    if not assertions:
        # For memory-safety-only harnesses, this can be acceptable if CBMC builtin checks are planned.
        has_builtin_checks = any(flag in manifest_cmd for flag in ["--bounds-check", "--pointer-check", "--signed-overflow-check"])
        severity = "medium" if not has_builtin_checks else "low"
        issues.append(
            issue(
                severity,
                "no_explicit_assertions",
                "The harness has no explicit assert(...) statements.",
                "This is acceptable only if the selected properties are intentionally checked through CBMC built-in checks; document that clearly.",
            )
        )
    else:
        positives.append(f"Harness contains {len(assertions)} explicit assertion(s).")

    for a in assertions:
        cls = a.get("classification")
        if cls == "trivial":
            issues.append(
                issue(
                    "high",
                    "trivial_assertion",
                    f"The assertion `{a['expression']}` is trivial and does not check the selected implementation behavior.",
                    "Replace trivial assertions with property-connected assertions or rely on CBMC built-in checks explicitly.",
                    a.get("evidence"),
                )
            )
        elif cls == "always_fails":
            issues.append(
                issue(
                    "high",
                    "always_failing_assertion",
                    f"The assertion `{a['expression']}` always fails and is likely a harness mistake.",
                    "Replace it with a meaningful property assertion or remove it.",
                    a.get("evidence"),
                )
            )

    functional_assertions = [a for a in assertions if a.get("classification") == "coefficient_functional_equality"]
    if functional_assertions:
        if code_uses_signed_small_int(code_summary, artifact_text) and code_has_coeff_addition(code_summary, artifact_text):
            issues.append(
                issue(
                    "medium",
                    "signed_overflow_risk_in_functional_assertion",
                    "The coefficient equality assertion may involve signed small-integer addition, so CBMC may report signed overflow unless valid input bounds are justified.",
                    "Separate memory-safety checking from arithmetic correctness, or add carefully justified coefficient preconditions before checking equality.",
                    functional_assertions[0].get("evidence"),
                    selected_ids,
                )
            )
        if "functional" not in " ".join(selected_types).lower() and "functional" not in json.dumps(selected, ensure_ascii=False).lower():
            issues.append(
                issue(
                    "low",
                    "assertion_not_clearly_selected_property",
                    "The harness contains a functional equality assertion, but the selected manifest properties appear mostly safety-focused.",
                    "Confirm whether functional correctness is intentionally selected for this run or move it into a separate experiment variant.",
                    functional_assertions[0].get("evidence"),
                )
            )

    # 8. CBMC command/check compatibility.
    recommended_flags = ["--bounds-check", "--pointer-check", "--unwinding-assertions"]
    missing_flags = [flag for flag in recommended_flags if flag not in manifest_cmd]
    if missing_flags:
        issues.append(
            issue(
                "medium",
                "missing_recommended_cbmc_flags",
                f"The recommended CBMC command/manifest does not visibly include: {', '.join(missing_flags)}.",
                "Add these checks unless the run intentionally excludes them and documents why.",
            )
        )
    else:
        positives.append("Recommended CBMC command includes bounds, pointer, and unwinding checks.")

    if loops:
        has_unwind = "--unwind" in manifest_cmd or any("unwind" in str(p).lower() for p in selected)
        add_check("loop_unwind_planned", has_unwind, "Loop unwind appears planned" if has_unwind else "Loop unwind not clearly planned", "medium")
        if not has_unwind:
            issues.append(
                issue(
                    "medium",
                    "missing_unwind_plan",
                    "The harness contains loop(s), but no clear CBMC unwind plan was found.",
                    "Use --unwind with --unwinding-assertions and document the selected bound.",
                    loops[0].get("evidence"),
                )
            )
        else:
            positives.append("Loop unwinding is planned through CBMC command/properties.")

    # 9. Nondeterministic input sanity.
    input_params = as_list(code_summary.get("inputs"))
    if input_params and not nondet_uses:
        issues.append(
            issue(
                "medium",
                "missing_nondeterministic_inputs",
                "The selected function has likely input parameters, but the harness does not use visible nondeterministic input generation.",
                "Initialize relevant input fields with nondeterministic values so CBMC explores more than one fixed test case.",
            )
        )
    elif nondet_uses:
        positives.append(f"Harness uses nondeterministic input function(s): {', '.join(sorted({u['function'] for u in nondet_uses}))}.")

    # 10. Array/bounds structural checks.
    selected_has_bounds = any(t in {"array_bounds", "memory_safety", "loop_bound"} for t in selected_types)
    if selected_has_bounds and not array_accesses and not loops:
        issues.append(
            issue(
                "medium",
                "safety_property_without_visible_accesses",
                "Safety/bounds properties are selected, but the harness has no visible array accesses or loops.",
                "Confirm the target call is enough for CBMC to check the implementation, and include source files in the CBMC command.",
            )
        )
    elif array_accesses:
        positives.append(f"Harness contains {len(array_accesses)} visible array access(es), useful for initialization/assertion review.")

    # 11. Constant consistency.
    if spec_n is not None:
        n_text = str(spec_n)
        uses_n_literal_or_symbol = n_text in artifact_text or re.search(r"\b(KYBER_N|MLKEM_N|MLK_N|N)\b", artifact_text)
        add_check(
            "polynomial_size_constant_used",
            bool(uses_n_literal_or_symbol),
            f"Spec N={spec_n}; harness appears to use N/KYBER_N/literal" if uses_n_literal_or_symbol else f"Spec N={spec_n}; harness does not visibly use compatible size constant",
            "medium",
        )
        if not uses_n_literal_or_symbol:
            issues.append(
                issue(
                    "medium",
                    "missing_polynomial_size_constant",
                    f"The spec summary contains N = {spec_n}, but the harness does not visibly use that bound or a known N macro.",
                    "Use the implementation's verified polynomial-size macro or an explicitly justified constant.",
                )
            )
        else:
            positives.append(f"Harness appears to use a polynomial-size bound compatible with spec N={spec_n}.")

    if spec_q is not None and coefficient_bound_assumptions:
        # Warn when q is copied as a numeric bound without more proof context.
        for a in coefficient_bound_assumptions:
            if str(spec_q) in a.get("expression", "") and not has_explicit_spec_bound:
                issues.append(
                    issue(
                        "medium",
                        "q_used_as_input_bound_without_context",
                        f"The assumption `{a['expression']}` appears to reuse q={spec_q} as an input bound, but modulus value alone may not define valid implementation input range.",
                        "Document exactly why q implies this precondition, or avoid using q as an automatic input bound.",
                        a.get("evidence"),
                    )
                )

    # 12. Alias awareness.
    output_params = as_list(code_summary.get("outputs_or_inouts"))
    if output_params and len(input_params) >= 1:
        alias_text = lower_artifact
        mentions_alias = any(word in alias_text for word in ["alias", "separation", "same object", "distinct"])
        if not mentions_alias:
            issues.append(
                issue(
                    "low",
                    "aliasing_not_discussed",
                    "The function has pointer inputs/outputs, but the harness/review material does not discuss aliasing.",
                    "Decide whether aliases like r == a or r == b are allowed by the implementation contract, and document the choice.",
                )
            )
        else:
            positives.append("Artifact text mentions aliasing/separation concerns.")

    # 13. Property coverage.
    property_coverage: List[Dict[str, Any]] = []
    for p in selected:
        p_id = str(p.get("id", "unknown"))
        p_type = str(p.get("type", "unknown"))
        p_text = json.dumps(p, ensure_ascii=False).lower()
        covered_by = []
        if p_type in {"array_bounds", "memory_safety", "pointer_validity", "input_pointer_validity", "output_pointer_validity"}:
            if any(flag in manifest_cmd for flag in ["--bounds-check", "--pointer-check"]):
                covered_by.append("cbmc_builtin_checks")
        if p_type in {"loop_bound", "array_bounds"} and "--unwind" in manifest_cmd:
            covered_by.append("unwind_plan")
        if "functional" in p_type or "equals" in p_text or "output coefficient" in p_text:
            if functional_assertions:
                covered_by.append("explicit_functional_assertion")
        property_coverage.append(
            {
                "property_id": p_id,
                "property_type": p_type,
                "coverage_status": "covered_candidate" if covered_by else "not_clearly_covered",
                "covered_by": covered_by,
            }
        )

    uncovered_high_priority = [
        c for c, p in zip(property_coverage, selected)
        if c["coverage_status"] == "not_clearly_covered" and str(p.get("priority", "")).lower() == "high"
    ]
    if uncovered_high_priority:
        issues.append(
            issue(
                "medium",
                "selected_property_not_clearly_covered",
                f"{len(uncovered_high_priority)} high-priority selected propertie(s) are not clearly covered by assertions or CBMC flags.",
                "Either add explicit assertions/checks or update the property selection for this artifact.",
                related_property_ids=[str(c["property_id"]) for c in uncovered_high_priority],
            )
        )
    elif property_coverage:
        positives.append("Selected properties have at least candidate coverage through CBMC flags or explicit assertions.")

    # 14. Manifest/artifact consistency.
    manifest_artifact_file = str(manifest.get("artifact_file", ""))
    if manifest_artifact_file and Path(manifest_artifact_file).name != artifact_path.name:
        issues.append(
            issue(
                "low",
                "manifest_artifact_filename_mismatch",
                f"Manifest artifact_file points to `{manifest_artifact_file}`, but this review inspected `{artifact_path}`.",
                "Confirm whether the current artifact was repaired/promoted and update the manifest/resolved config if needed.",
            )
        )

    # 15. Unsupported broad claims.
    broad_claim_patterns = [
        r"fully\s+prove[sd]?\s+ml-?kem",
        r"complete\s+proof\s+of\s+ml-?kem",
        r"formally\s+verified\s+entire",
        r"ai\s+proved",
    ]
    for pat in broad_claim_patterns:
        for line_no, line, _ in find_lines_matching(artifact_text, pat, flags=re.I):
            issues.append(
                issue(
                    "high",
                    "unsafe_overclaim_in_artifact_text",
                    "The artifact text appears to contain an unsafe proof overclaim.",
                    "Rewrite the comment/output to say this is only a candidate artifact checked under selected assumptions.",
                    evidence_for_line(artifact_path, line_no, line),
                )
            )

    # Deduplicate issues by type+message+line.
    seen = set()
    deduped: List[Dict[str, Any]] = []
    for it in issues:
        ev = it.get("evidence", {}) if isinstance(it.get("evidence"), dict) else {}
        key = (it.get("severity"), it.get("type"), it.get("message"), ev.get("start_line"))
        if key not in seen:
            seen.add(key)
            deduped.append(it)
    issues = deduped

    return {
        "target_function": target_function,
        "harness_function": harness_function,
        "selected_property_types": selected_types,
        "selected_property_ids": selected_ids,
        "assumptions": assumptions,
        "assertions": assertions,
        "includes": includes,
        "loops": loops,
        "array_accesses": array_accesses,
        "nondet_uses": nondet_uses,
        "function_calls": calls,
        "target_calls": target_calls,
        "property_coverage": property_coverage,
        "issues": issues,
        "positive_findings": positives,
        "checklist": checklist,
        "manifest_command_seen": manifest_cmd,
        "spec_constants_seen": {"N": spec_n, "q": spec_q},
        "iteration": iteration,
    }


