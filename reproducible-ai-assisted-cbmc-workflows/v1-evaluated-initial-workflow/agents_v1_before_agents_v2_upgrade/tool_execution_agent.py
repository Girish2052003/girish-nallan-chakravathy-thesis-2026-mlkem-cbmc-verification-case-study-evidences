#!/usr/bin/env python3
"""
Formal Tool Execution Agent (Agent 7)
=====================================

Purpose
-------
Runs the selected formal verification tool, currently CBMC, on the candidate
formal-verification artifact generated by Agent 5 and reviewed by Agent 6.

This agent is intentionally careful:
- It treats generated harnesses as candidate artifacts only.
- It does not interpret a CBMC pass as "full ML-KEM is proved".
- It saves every command, output, status, and warning for reproducibility.
- A CBMC verification failure is a research result, not a Python crash.

Expected inputs in run directory
--------------------------------
- 04_generated_harness.c or 08_repaired_harness.c
- 04_artifact_manifest.json, if available
- 05_critic_review.json, if available
- run_config.resolved.json, if available
- original config JSON

Expected outputs in run directory
---------------------------------
- 06_cbmc_output.txt
- 06_cbmc_status.json
- 06_cbmc_command.txt
- 06_tool_execution.md
- 06_cbmc_property_results.json
- agent_status/06_tool_execution_status.json
- tool_outputs/cbmc_output_iteration_<N>.txt

CLI example
-----------
python3 agents/tool_execution_agent.py \
  --config configs/poly_add_run.json \
  --run-dir runs/run_001_poly_add \
  --iteration 0 \
  --artifact 04_generated_harness.c
"""

